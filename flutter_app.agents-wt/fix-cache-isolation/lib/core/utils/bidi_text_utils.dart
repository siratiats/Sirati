/// Utilities for bidirectional text isolation, base direction detection,
/// and mixed-script handling in editors (SIRATI-27).
///
/// Follows Unicode Bidirectional Algorithm (UAX #9) standards.
class BidiTextUtils {
  BidiTextUtils._();

  /// Unicode Directional Formatting Characters
  static const lrm = '\u200E'; // Left-to-Right Mark
  static const rlm = '\u200F'; // Right-to-Left Mark
  static const lri = '\u2066'; // Left-to-Right Isolate
  static const rli = '\u2067'; // Right-to-Left Isolate
  static const pdi = '\u2069'; // Pop Directional Isolate
  static const lre = '\u202A'; // Left-to-Right Embedding
  static const pdf = '\u202C'; // Pop Directional Formatting

  // Regex identifying strong Arabic / Hebrew RTL script characters
  static final RegExp _rtlCharRegex = RegExp(
    r'[\u0590-\u05FF\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]',
  );

  // Regex identifying strong Latin / Western LTR script characters
  static final RegExp _ltrCharRegex = RegExp(r'[A-Za-z]');

  // Common LTR token patterns that appear inside Arabic CV prose:
  // email, URL, phone numbers, tech acronyms, slash-separated paths/terms
  static final RegExp _embeddedLtrPattern = RegExp(
    r'((?:https?://|www\.)[^\s]+|[\w.+-]+@[\w-]+\.[\w.-]+|\+?[0-9][0-9\s-]{6,}[0-9]|[A-Za-z0-9+#./-]+(?:\s+[A-Za-z0-9+#./-]+)*)',
  );

  /// Detects the base paragraph direction based on the first strong directional character (UAX #9).
  ///
  /// Returns [TextDirection.rtl] if the first strong character is Arabic/RTL,
  /// [TextDirection.ltr] if it is Latin/LTR, or [fallback] if neutral/empty.
  static TextDirection detectBaseDirection(
    String? text, {
    TextDirection fallback = TextDirection.rtl,
  }) {
    if (text == null || text.isEmpty) return fallback;

    for (int i = 0; i < text.length; i++) {
      final char = text[i];
      if (_rtlCharRegex.hasMatch(char)) {
        return TextDirection.rtl;
      }
      if (_ltrCharRegex.hasMatch(char)) {
        return TextDirection.ltr;
      }
    }
    return fallback;
  }

  /// Wraps an LTR run in Left-to-Right Isolate (`\u2066` ... `\u2069`)
  /// so it does not scramble surrounding Arabic text or punctuation.
  static String isolateLtr(String text) {
    if (text.isEmpty) return text;
    return '$lri$text$pdi';
  }

  /// Wraps an RTL run in Right-to-Left Isolate (`\u2067` ... `\u2069`).
  static String isolateRtl(String text) {
    if (text.isEmpty) return text;
    return '$rli$text$pdi';
  }

  /// Isolates embedded technical terms, emails, URLs, and phone numbers inside
  /// an Arabic string using directional isolation markers.
  static String isolateEmbeddedLtrInArabic(String text) {
    if (text.isEmpty) return text;

    return text.replaceAllMapped(_embeddedLtrPattern, (match) {
      final matchedText = match.group(0) ?? '';
      // Only isolate if it contains Latin letters, URL schemes, or phone format
      if (_ltrCharRegex.hasMatch(matchedText) ||
          matchedText.contains('@') ||
          matchedText.contains('http') ||
          matchedText.startsWith('+')) {
        return '$lri$matchedText$pdi';
      }
      return matchedText;
    });
  }

  /// Strips dangling unclosed directional control characters to ensure
  /// clean logical storage in the database and JSON.
  static String sanitizeBidiControls(String text) {
    if (text.isEmpty) return text;
    return text.replaceAll(
        RegExp(r'[\u200E\u200F\u202A-\u202E\u2066-\u2069]'), '');
  }

  /// Normalizes Arabic presentation forms into canonical logical Unicode code points.
  /// Decomposes all forms in Presentation Forms-A (FB50..FDFF) and Forms-B (FE70..FEFF).
  static String toLogicalUnicode(String text) {
    if (text.isEmpty) return text;

    final buffer = StringBuffer();
    for (int i = 0; i < text.length; i++) {
      final code = text.codeUnitAt(i);
      final mapped = _presentationFormsMap[code];
      if (mapped != null) {
        buffer.write(mapped);
      } else {
        buffer.write(text[i]);
      }
    }
    return buffer.toString();
  }

