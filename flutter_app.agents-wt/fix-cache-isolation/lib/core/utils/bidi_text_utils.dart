/// Text input formatter that ensures clean logical Unicode is preserved
/// and prevents cursor glitches in mixed-direction text inputs.
class LogicalBidiInputFormatter extends TextInputFormatter {
  const LogicalBidiInputFormatter();

  @override
  TextEditingValue formatEditUpdate(
    TextEditingValue oldValue,
    TextEditingValue newValue,
  ) {
    final text = newValue.text;
    if (text.isEmpty) return newValue;

    // Fast check if any character needs decomposition
    bool hasPresentationForms = false;
    for (int i = 0; i < text.length; i++) {
      final code = text.codeUnitAt(i);
      if ((code >= 0xFB50 && code <= 0xFDFF) ||
          (code >= 0xFE70 && code <= 0xFEFF)) {
        hasPresentationForms = true;
        break;
      }
    }

    if (!hasPresentationForms) {
      return newValue;
    }

    final buffer = StringBuffer();
    final offsetMap = List<int>.filled(text.length + 1, 0);

    for (int i = 0; i < text.length; i++) {
      offsetMap[i] = buffer.length;
      final code = text.codeUnitAt(i);
      final mapped = BidiTextUtils._presentationFormsMap[code];
      if (mapped != null) {
        buffer.write(mapped);
      } else {
        buffer.write(text[i]);
      }
    }
    offsetMap[text.length] = buffer.length;

    final normalized = buffer.toString();

    int mapOffset(int rawOffset) {
      if (rawOffset < 0) return rawOffset;
      if (rawOffset >= offsetMap.length) return normalized.length;
      return offsetMap[rawOffset];
    }

    final newBase = mapOffset(newValue.selection.baseOffset);
    final newExtent = mapOffset(newValue.selection.extentOffset);
    final newSelection = newValue.selection.copyWith(
      baseOffset: newBase,
      extentOffset: newExtent,
    );

    TextRange newComposing = TextRange.empty;
    if (newValue.composing.isValid && !newValue.composing.isCollapsed) {
      final compStart = mapOffset(newValue.composing.start);
      final compEnd = mapOffset(newValue.composing.end);
      newComposing = TextRange(start: compStart, end: compEnd);
    }

    return TextEditingValue(
      text: normalized,
      selection: newSelection,
      composing: newComposing,
    );
  }
}
